#!/usr/bin/env bun
// Writes the Story directory tree's first snapshot (People 001) as Swift, so
// Story can activate the tree without encoding collection tables itself.
//
//   bun tools/directory-seed.ts          rewrite the Swift file
//   bun tools/directory-seed.ts --check  exit 1 if it is stale
//
// The tree's content is tools/directory-seed/: `_index.md`, and the People and
// Trees collections with no rows. Changing a schema changes its fingerprint,
// so a directory already activated keeps the old one until Story migrates it.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileLogicalSchema, encodeCollection } from "@ovst/collection-schema";
import { encodeProtocolDirectory, hashObject, type ProtocolDirectory, type ProtocolDirectoryEntry } from "@ovst/protocol";

const source = join(import.meta.dir, "directory-seed");
export const directorySeedSwiftPath = join(import.meta.dir, "../swift/Packages/OverstoryClient/Sources/OverstoryClient/PersonalDirectorySeed.swift");

/** The directory tree's first snapshot. */
export function directorySeed(): { root: string; objects: Map<string, Uint8Array> } {
  const objects = new Map<string, Uint8Array>();
  const put = (bytes: Uint8Array) => {
    const hash = hashObject(bytes);
    objects.set(hash, bytes);
    return hash;
  };
  const directory = (entries: ProtocolDirectoryEntry[], collection?: ProtocolDirectory["collection"]) =>
    put(encodeProtocolDirectory({ type: "directory", entries, ...(collection ? { collection } : {}) }));
  /** An empty collection folder holding `schema.usl`. */
  const collection = (name: string): ProtocolDirectoryEntry => {
    const schema = readFileSync(join(source, name, "schema.usl"));
    const encoded = encodeCollection(compileLogicalSchema(schema), {});
    for (const [hash, bytes] of encoded.objects) objects.set(hash, bytes);
    return { name, directory: directory([{ name: "schema.usl", file: put(schema) }], encoded.reference) };
  };
  const root = directory([
    { name: "_index.md", file: put(readFileSync(join(source, "_index.md"))) },
    collection("people"),
    collection("trees"),
  ]);
  return { root, objects };
}

/** The seed as the Swift file Story builds. */
export function directorySeedSwift(): string {
  const { root, objects } = directorySeed();
  const lines = [...objects].sort(([a], [b]) => a.localeCompare(b))
    .map(([hash, bytes]) => `        ("${hash}", "${Buffer.from(bytes).toString("base64")}"),`);
  return `// Generated by tools/directory-seed.ts from tools/directory-seed/. Do not edit.

enum PersonalDirectorySeed {
    static let root = "${root}"
    static let objects: [(hash: String, base64: String)] = [
${lines.join("\n")}
    ]
}
`;
}

if (import.meta.main) {
  const swift = directorySeedSwift();
  if (!process.argv.includes("--check")) writeFileSync(directorySeedSwiftPath, swift);
  else if (readFileSync(directorySeedSwiftPath, "utf8") !== swift) {
    console.error(`${directorySeedSwiftPath} is stale; run bun tools/directory-seed.ts`);
    process.exit(1);
  }
}
